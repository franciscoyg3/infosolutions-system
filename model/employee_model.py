class EmployeeModel:
    def __init__(self, name, position, base_salary, bonus=0, id=None):
        # Trims the text fields, then validates; the first failed check raises ValueError.
        # id stays None until the employee is saved or loaded from the database.
        name, position = name.strip(), position.strip()
        if not name or not position:
            raise ValueError("Empty values are not allowed.")
        if base_salary < 0 or bonus < 0:
            raise ValueError("Salary and bonus cannot be negative.")

        self.id, self.name = id, name
        self.position, self.base_salary, self.bonus = position, base_salary, bonus

    @property
    def total_salary(self):
        # Computed on access from its two parts, so it is never stored in the database
        return self.base_salary + self.bonus

    def add_employee(self, db):
        # The connection context manager commits on success and rolls back if an exception occurs
        with db.connect() as con:
            cur = con.execute(
                "INSERT INTO employees (name, position, base_salary, bonus) VALUES (?,?,?,?)",
                (self.name, self.position, self.base_salary, self.bonus)
            )
            # Stores the id generated by the database on this instance
            self.id = cur.lastrowid

    @staticmethod
    def remove_employee(db, id):
        with db.connect() as con:
            cur = con.execute(
                "DELETE FROM employees WHERE id=?", (id,)
            )
            # rowcount 0 means no employee had that id
            if cur.rowcount == 0:
                raise ValueError("Employee not found.")

    @staticmethod
    def list_employees(db):
        with db.connect() as con:
            rows = con.execute(
                "SELECT id, name, position, base_salary, bonus FROM employees"
            ).fetchall()
        # Rebuilds each row as an EmployeeModel, so stored data goes through the same validation
        return [
            EmployeeModel(name, position, base_salary, bonus, id)
            for id, name, position, base_salary, bonus in rows
        ]

    @staticmethod
    def calculate_payroll(db):
        with db.connect() as con:
            # Sums base salary plus bonus for every employee; COALESCE treats a NULL
            # bonus as 0 and makes an empty table return 0 instead of NULL
            result = con.execute(
                "SELECT COALESCE(SUM(base_salary + COALESCE(bonus, 0)), 0) FROM employees"
            ).fetchone()
        return result[0]

    @staticmethod
    def get_highest_paid(db):
        with db.connect() as con:
            # The subquery finds the highest total (salary + bonus); the outer query
            # returns every employee with that total, so ties are all included.
            # An empty table returns no rows, i.e. an empty list
            rows = con.execute("""
                SELECT id, name, position, base_salary, COALESCE(bonus, 0)
                FROM employees
                WHERE base_salary + COALESCE(bonus, 0) = (
                    SELECT MAX(base_salary + COALESCE(bonus, 0)) FROM employees
                )
            """).fetchall()
        return [
            EmployeeModel(name, position, base_salary, bonus, id)
            for id, name, position, base_salary, bonus in rows
        ]