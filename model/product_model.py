class ProductModel:
    def __init__(self, name, price, quantity, id=None):
        # Trims the name, then validates; the first failed check raises ValueError.
        # id stays None until the product is saved or loaded from the database.
        name = name.strip()
        if not name:
            raise ValueError("Invalid product name.")
        if price < 0:
            raise ValueError("Invalid price.")
        if quantity < 0:
            raise ValueError("Invalid quantity.")

        self.id, self.name = id, name
        self.price, self.quantity = price, quantity

    def add_product(self, db):
        # The connection context manager commits on success and rolls back if an exception occurs
        with db.connect() as con:
            cur = con.execute(
                "INSERT INTO products (name, price, quantity) VALUES (?,?,?)",
                (self.name, self.price, self.quantity)
            )
            # Stores the id generated by the database on this instance
            self.id = cur.lastrowid

    @staticmethod
    def remove_product(db, id):
        with db.connect() as con:
            cur = con.execute(
                "DELETE FROM products WHERE id=?",
                (id,)
            )
            # rowcount 0 means no product had that id
            if cur.rowcount == 0:
                raise ValueError("Product not found.")

    @staticmethod
    def list_products(db):
        with db.connect() as con:
            rows = con.execute(
                "SELECT id, name, price, quantity FROM products"
            ).fetchall()
        # Rebuilds each row as a ProductModel, so stored data goes through the same validation
        return [ProductModel(n, p, q, id) for id, n, p, q in rows]

    @staticmethod
    def update_stock(db, id, new_quantity):
        # Validates before opening the connection, so a bad quantity never reaches the database
        if new_quantity < 0:
            raise ValueError("Invalid quantity.")
        with db.connect() as con:
            # Overwrites the stock with the new value instead of adding to it
            cur = con.execute(
                "UPDATE products SET quantity=? WHERE id=?",
                (new_quantity, id)
            )
            if cur.rowcount == 0:
                raise ValueError("Product not found.")